using System.Net;
using System.Net.Http.Json;
using System.Text.Json;

namespace Fitzobit.Tests.Web;

/// <summary>The Add Customer workflow through the real HTTP pipeline: drop-downs from the database, end-date preview, create, pause.</summary>
public class CustomerApiTests
{
    private static async Task<JsonElement> JsonAsync(HttpResponseMessage response)
    {
        HttpAssert.Status(HttpStatusCode.OK, response);
        return await response.Content.ReadFromJsonAsync<JsonElement>();
    }

    private static int IdOf(JsonElement options, string list, string code) =>
        options.GetProperty(list).EnumerateArray().Single(o => o.GetProperty("code").GetString() == code).GetProperty("id").GetInt32();

    [Fact]
    public async Task Dropdowns_preview_create_and_pause_a_customer()
    {
        using var host = new WebTestHost();
        var admin = await host.SetupAdminAsync();

        var options = await JsonAsync(await admin.GetAsync("/api/dictionaries"));
        Assert.Equal(["Veg", "With Egg", "None"], options.GetProperty("preference").EnumerateArray().Select(o => o.GetProperty("displayName").GetString()));
        Assert.Equal(5, options.GetProperty("mealType").GetArrayLength());
        var weekly = IdOf(options, "frequency", "WEEKLY");

        var nextMonday = DateOnly.FromDateTime(DateTime.UtcNow.AddHours(5.5)).AddDays(1);
        while (nextMonday.DayOfWeek != DayOfWeek.Monday) nextMonday = nextMonday.AddDays(1);
        var preview = await JsonAsync(await admin.GetAsync($"/api/customers/schedule?frequencyId={weekly}&startDate={nextMonday:yyyy-MM-dd}"));
        Assert.Equal(nextMonday.AddDays(5).ToString("yyyy-MM-dd"), preview.GetProperty("endDate").GetString());
        Assert.Equal(6, preview.GetProperty("deliveryDays").GetInt32());

        var sunday = nextMonday.AddDays(-1);
        HttpAssert.Status(HttpStatusCode.Conflict, await admin.GetAsync($"/api/customers/schedule?frequencyId={weekly}&startDate={sunday:yyyy-MM-dd}"));

        var package = new
        {
            preferenceId = IdOf(options, "preference", "VEG"),
            mealTypeId = IdOf(options, "mealType", "MEDIUM"),
            quantity = 1,
            frequencyId = weekly,
            startDate = nextMonday.ToString("yyyy-MM-dd"),
            endDate = "2099-01-01", pausedCount = 3 // ignored: never taken from the client
        };
        var request = new
        {
            customerName = "Anitha Raman",
            phoneNumber = "98765 43210",
            address = "7 Main Road, RS Puram, Coimbatore",
            pincode = "641002",
            preferredDeliveryTime = "07:30:00",
            packages = new[] { package },
            note = "Gate code 1234",
            customerId = "HACKED-1" // ignored: generated by the server
        };
        var created = await JsonAsync(await admin.PostAsync("/api/customers", request));
        Assert.Equal("FITZ-000001", created.GetProperty("customerId").GetString());
        var id = created.GetProperty("id").GetInt32();

        var detail = await JsonAsync(await admin.GetAsync($"/api/customers/{id}"));
        Assert.Equal(("FITZ-000001", "07:30:00", "Active"), (detail.GetProperty("customerId").GetString(),
            detail.GetProperty("preferredDeliveryTime").GetString(), detail.GetProperty("status").GetString()));
        var firstPackage = detail.GetProperty("packages")[0];
        Assert.Equal(("Weekly", 0, nextMonday.AddDays(5).ToString("yyyy-MM-dd")), (firstPackage.GetProperty("frequency").GetString(),
            firstPackage.GetProperty("pausedCount").GetInt32(), firstPackage.GetProperty("endDate").GetString()));
        var note = detail.GetProperty("notes")[0];
        Assert.Equal(("Gate code 1234", true), (note.GetProperty("text").GetString(), note.GetProperty("canEdit").GetBoolean()));
        Assert.Equal(JsonValueKind.Null, detail.GetProperty("latitude").ValueKind);

        // A second package, a pause of both on Saturday, a second note.
        var oats = await JsonAsync(await admin.PostAsync($"/api/customers/{id}/packages",
            new { preferenceId = IdOf(options, "preference", "WITH-EGG"), mealTypeId = IdOf(options, "mealType", "OATS"), quantity = 2, frequencyId = weekly,
                startDate = nextMonday.ToString("yyyy-MM-dd") }));
        var saturday = nextMonday.AddDays(5);
        var pause = await JsonAsync(await admin.PostAsync($"/api/customers/{id}/pauses", new { date = saturday.ToString("yyyy-MM-dd"), reason = "Out of town" }));
        Assert.Equal(2, pause.GetProperty("packages").GetArrayLength());
        Assert.All(pause.GetProperty("packages").EnumerateArray(),
            p => Assert.Equal(nextMonday.AddDays(7).ToString("yyyy-MM-dd"), p.GetProperty("newEndDate").GetString())); // Saturday → Monday
        HttpAssert.Status(HttpStatusCode.OK, await admin.PostAsync($"/api/customers/{id}/notes", new { text = "Less spice" }));

        // The added package starts next Monday, so it can still be deleted.
        HttpAssert.Status(HttpStatusCode.NoContent, await admin.DeleteAsync($"/api/customers/packages/{oats.GetProperty("id").GetInt32()}"));

        var invalid = await admin.PostAsync("/api/customers", new { customerName = "X", phoneNumber = "1", address = "", pincode = "1" });
        HttpAssert.Status(HttpStatusCode.Conflict, invalid);
        Assert.Contains("Customer name", await ApiClient.DetailAsync(invalid));
        var noPackage = await admin.PostAsync("/api/customers", new { request.customerName, request.phoneNumber, request.address, request.pincode,
            request.preferredDeliveryTime, packages = Array.Empty<object>() });
        HttpAssert.Status(HttpStatusCode.Conflict, noPackage);
        Assert.Contains("Add at least one package", await ApiClient.DetailAsync(noPackage));

        var list = await JsonAsync(await admin.GetAsync("/api/customers?search=anitha"));
        Assert.Equal(1, list.GetProperty("total").GetInt32());
        var item = list.GetProperty("items")[0];
        Assert.Equal(("Medium", 1), (item.GetProperty("packages")[0].GetProperty("mealType").GetString(), item.GetProperty("packages").GetArrayLength()));
        Assert.Equal(2, (await JsonAsync(await admin.GetAsync($"/api/customers/{id}"))).GetProperty("notes").GetArrayLength());
    }

    [Fact]
    public async Task Administrators_manage_dropdown_values_in_settings()
    {
        using var host = new WebTestHost();
        var admin = await host.SetupAdminAsync();

        var created = await JsonAsync(await admin.PostAsync("/api/dictionaries/Frequency", new { displayName = "Fortnightly", numericValue = 12 }));
        Assert.Equal("FORTNIGHTLY", created.GetProperty("code").GetString());
        var id = created.GetProperty("id").GetInt32();

        await JsonAsync(await admin.PutAsync($"/api/dictionaries/entries/{id}", new { displayName = "Every two weeks", numericValue = 12, isActive = false }));
        var frequencies = await JsonAsync(await admin.GetAsync("/api/dictionaries/Frequency"));
        var entry = frequencies.EnumerateArray().Single(e => e.GetProperty("id").GetInt32() == id);
        Assert.Equal(("Every two weeks", false), (entry.GetProperty("displayName").GetString(), entry.GetProperty("isActive").GetBoolean()));

        var active = await JsonAsync(await admin.GetAsync("/api/dictionaries"));
        Assert.DoesNotContain(active.GetProperty("frequency").EnumerateArray(), o => o.GetProperty("id").GetInt32() == id);

        var ids = frequencies.EnumerateArray().Select(e => e.GetProperty("id").GetInt32()).Reverse().ToList();
        HttpAssert.Status(HttpStatusCode.NoContent, await admin.PutAsync("/api/dictionaries/Frequency/order", new { ids }));
        HttpAssert.Status(HttpStatusCode.NoContent, await admin.Http.DeleteAsync($"/api/dictionaries/entries/{id}"));
        HttpAssert.Status(HttpStatusCode.BadRequest, await admin.GetAsync("/api/dictionaries/NotAType"));
    }

    [Fact]
    public async Task Retired_import_catalogue_and_plan_endpoints_are_gone()
    {
        using var host = new WebTestHost();
        var admin = await host.SetupAdminAsync();

        foreach (var url in new[] { "/api/imports", "/api/imports/template", "/api/catalogue", "/api/catalogue/plans", "/api/catalogue/plan-options" })
            HttpAssert.Status(HttpStatusCode.NotFound, await admin.GetAsync(url));
    }
}
